export function getSkillTreeForClass(cls: SkillClass): readonly SkillNodeDef[] {
  switch (cls) {
    case 'warrior':
      return WARRIOR_SKILL_TREE;
    case 'mage':
      return MAGE_SKILL_TREE;
    case 'archer':
      return ARCHER_SKILL_TREE;
    case 'necromancer':
      return NECROMANCER_SKILL_TREE;
  }
}

export function getSkillNode(id: string): SkillNodeDef | undefined {
  return ALL_SKILL_NODES.find((n) => n.id === id);
}
